# Генерация site\tvserver.js — разовые настройки Lampa на каждом устройстве (TorrServer + парсер).
# Используется install.ps1 и панелью. Увеличение версии заставляет устройства применить настройки заново.

function Get-TvServerJsVersion([string]$SiteDir) {
    $f = Join-Path $SiteDir 'tvserver.js'
    if (-not (Test-Path $f)) { return 0 }
    $m = [regex]::Match((Get-Content $f -Raw -Encoding UTF8), "var VERSION = '(\d+)'")
    if ($m.Success) { return [int]$m.Groups[1].Value } else { return 0 }
}

function Write-TvServerJs([string]$SiteDir, [string]$Ip, [int]$TorrPort, [string]$JackettUrl, [int]$Version) {
    $defs = [ordered]@{ torrserver_url = "http://${Ip}:$TorrPort" }
    if ($JackettUrl) {
        $defs.parser_use = 'true'; $defs.parser_torrent_type = 'jackett'
        $defs.jackett_url = $JackettUrl; $defs.jackett_key = ''; $defs.parse_timeout = '30'
    }
    $lines = ($defs.Keys | ForEach-Object { "        ${_}: '" + ($defs[$_] -replace "'", "\'") + "'" }) -join ",`n"
    $js = @"
// tv_server: one-time default settings for Lampa served from this PC (generated by tv_server).
// Runs before Lampa starts; writes the values once per device and version (marker key below),
// so anything changed later in Lampa settings is kept until VERSION is increased.
(function () {
    var VERSION = '$Version';
    var MARKER = 'tvserver_defaults';
    var defaults = {
$lines
    };
    try {
        var ls = window.localStorage;
        if (ls.getItem(MARKER) === VERSION) return;
        for (var k in defaults) {
            if (Object.prototype.hasOwnProperty.call(defaults, k)) ls.setItem(k, defaults[k]);
        }
        ls.setItem(MARKER, VERSION);
    } catch (e) {
        if (window.console) console.log('tvserver.js', e);
    }
})();
"@
    [IO.File]::WriteAllText((Join-Path $SiteDir 'tvserver.js'), $js.Replace("`r`n", "`n"), (New-Object Text.UTF8Encoding $false))
}

# Подключает tvserver.js в index.html (перед loader.js), если ещё не подключён. Побайтово, без смены кодировки.
function Add-TvServerJsTag([string]$SiteDir) {
    $index = Join-Path $SiteDir 'index.html'
    $enc = [Text.Encoding]::GetEncoding(28591)
    $t = $enc.GetString([IO.File]::ReadAllBytes($index))
    if ($t.Contains('tvserver.js')) { return }
    $anchor = '<script src="./loader.js"></script>'
    if (([regex]::Matches($t, [regex]::Escape($anchor))).Count -ne 1) { throw 'В index.html не найдена строка подключения loader.js' }
    $nl = if ($t.Contains("`r`n")) { "`r`n" } else { "`n" }
    $t = $t.Replace($anchor, '<script src="./tvserver.js"></script>' + $nl + '    ' + $anchor)
    [IO.File]::WriteAllBytes($index, $enc.GetBytes($t))
}
